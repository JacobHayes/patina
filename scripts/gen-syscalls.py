#!/usr/bin/env python3
"""gen-syscalls.py: write crates/patina-proto/src/nr/{x86_64,aarch64}.rs from the kernel's tables.

    python3 scripts/gen-syscalls.py LINUX/arch/x86/entry/syscalls/syscall_64.tbl LINUX/scripts/syscall.tbl

Run by hand when the kernel adds calls. Every name either architecture has gets one constant in
both files: its number, or `absent(k)` (k: its number on the other architecture) where this one
lacks it. NAMES holds each architecture's own numbers.
"""
import os
import sys

# The ABIs each architecture's 64-bit table takes (arch/x86/entry/syscalls/Makefile.syscalls,
# arch/arm64/kernel/Makefile.syscalls).
ABIS = {
    "x86_64": {"common", "64"},
    "aarch64": {"common", "64", "renameat", "rlimit", "memfd_secret"},
}


def table(path, abis):
    nums = {}
    for line in open(path):
        f = line.split()
        if not f or f[0].startswith("#") or f[1] not in abis:
            continue
        nr, name = int(f[0]), f[2]
        if name in nums or nr in nums.values():
            sys.exit(f"{path}: {name} {nr} given twice")
        nums[name] = nr
    return nums


def write(path, arch, src, own, other):
    count = max(own.values()) + 1
    names = sorted(set(own) | set(other), key=lambda n: (n not in own, own.get(n, other.get(n))))
    out = [
        f"//! System call numbers on {arch}, by name. Generated by `scripts/gen-syscalls.py` from the",
        f"//! kernel's `{src}`; do not edit. A call {arch} lacks is `absent(k)`, k its",
        "//! number on the other architecture.",
        "",
    ]
    if set(other) - set(own):
        out += ["use super::absent;", ""]
    out += [f"pub const NR_COUNT: usize = {count};", ""]
    for n in names:
        v = str(own[n]) if n in own else f"absent({other[n]})"
        out.append(f"pub const {n.upper()}: u64 = {v};")
    out += [
        "",
        "/// Names by number; numbers no call has are `None`.",
        "pub static NAMES: [Option<&str>; NR_COUNT] = {",
        "    let mut n: [Option<&str>; NR_COUNT] = [None; NR_COUNT];",
    ]
    for name, nr in sorted(own.items(), key=lambda kv: kv[1]):
        out.append(f'    n[{nr}] = Some("{name}");')
    out += ["    n", "};", "", "/// Every constant above with its name, for the tests.", "#[cfg(test)]",
            "pub(crate) const BY_NAME: &[(&str, u64)] = &["]
    for n in names:
        out.append(f'    ("{n}", {n.upper()}),')
    out += ["];", ""]
    open(path, "w").write("\n".join(out))


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__.strip().split("\n\n")[1])
    x86 = table(sys.argv[1], ABIS["x86_64"])
    arm = table(sys.argv[2], ABIS["aarch64"])
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "crates", "patina-proto", "src", "nr")
    write(os.path.join(root, "x86_64.rs"), "x86_64", "arch/x86/entry/syscalls/syscall_64.tbl", x86, arm)
    write(os.path.join(root, "aarch64.rs"), "aarch64", "scripts/syscall.tbl", arm, x86)
    print(f"x86_64: {len(x86)} calls; aarch64: {len(arm)} calls, {len(set(x86) - set(arm))} absent; "
          f"x86_64 absent: {len(set(arm) - set(x86))}")


main()
