const fn rows() -> [SyscallRow; Syscall::ALL.len()] {
    let mut rows = [disposition(Syscall::ALL[0]); Syscall::ALL.len()];
    let mut i = 0;
    while i < rows.len() {
        rows[i] = disposition(Syscall::ALL[i]);
        i += 1;
    }
    rows
}

