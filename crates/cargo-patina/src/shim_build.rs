/// Environment the C compiler reads that changes an object's bytes without
/// changing its command line: the macOS SDK and deployment target, and the
/// include search paths.
const COMPILER_ENVIRONMENT: &[&str] = &[
    "SDKROOT",
    "MACOSX_DEPLOYMENT_TARGET",
    "CPATH",
    "C_INCLUDE_PATH",
];

/// Hash the inputs that determine a shim object's bytes: the compiler identity
/// and its `--version` banner, the [`COMPILER_ENVIRONMENT`], the target triple,
/// the object name, the exact cc flags, and the embedded C header/source. The
/// staged path changes only when one of these does, so a rebuild of the same
/// Patina against the same toolchain reuses the object and the `-Clink-arg`
/// path stays stable.
fn shim_object_hash(
    cc: &OsStr,
    object: &ShimObject,
    target: &str,
    defines: &[String],
) -> Result<String, CliError> {
    shim_object_hash_in(cc, object, target, defines, |name| env::var_os(name))
}

fn shim_object_hash_in(
    cc: &OsStr,
    object: &ShimObject,
    target: &str,
    defines: &[String],
    environment: impl Fn(&str) -> Option<OsString>,
) -> Result<String, CliError> {
    let version = Command::new(cc)
        .arg("--version")
        .output()
        .map_err(|error| CliError(format!("failed to query C compiler {cc:?}: {error}")))?;
    if !version.status.success() {
        return Err(CliError(format!("C compiler {cc:?} --version failed")));
    }
    let mut hasher = Sha256::new();
    hash_os(&mut hasher, cc);
    hash_bytes(&mut hasher, &version.stdout);
    for name in COMPILER_ENVIRONMENT {
        hash_bytes(&mut hasher, name.as_bytes());
        match environment(name) {
            Some(value) => {
                hasher.update([1]);
                hash_os(&mut hasher, &value);
            }
            None => hasher.update([0]),
        }
    }
    hash_bytes(&mut hasher, target.as_bytes());
    hash_bytes(&mut hasher, object.object_name.as_bytes());
    for flag in object.cc_flags {
        hash_bytes(&mut hasher, flag.as_bytes());
    }
    for define in defines {
        hash_bytes(&mut hasher, define.as_bytes());
    }
    if let Some((header_name, header_source)) = object.header {
        hash_bytes(&mut hasher, header_name.as_bytes());
        hash_bytes(&mut hasher, header_source.as_bytes());
    }
    for (relative, source) in object.companion_sources {
        hash_bytes(&mut hasher, relative.as_bytes());
        hash_bytes(&mut hasher, source.as_bytes());
    }
    hash_bytes(&mut hasher, object.source.as_bytes());
    Ok(hex(&hasher.finalize()))
}

/// Stage the SanitizerCoverage hook object this build's instrumentation calls
/// for, and announce it on stdout (stderr under `--format json`, so the JSON
/// document stays parseable).
///
/// `None` for a plain build: its link recipe then contains no SanitizerCoverage
/// flags and no hook object, so a plain native build is byte-for-byte the build
/// it was before any instrumentation existed.
pub(super) fn stage_instrumentation_object(
    shim: &BuiltNativeShim,
    instrumentation: GuestInstrumentation,
    host_target: &str,
) -> Result<Option<PathBuf>, CliError> {
    let (object, defines) = match instrumentation {
        GuestInstrumentation::None => return Ok(None),
        GuestInstrumentation::YieldPoints => (&PATINA_YIELD_OBJECT, Vec::new()),
        GuestInstrumentation::CoveragePoints { stride } => (
            &PATINA_COV_OBJECT,
            // Baked in at compile time, not read from the environment: the
            // sampling rate is part of the schedule policy, so it must be a
            // property of the BINARY (which the run side reads back out of the
            // marker) rather than something a later run could change under a
            // recorded trace.
            vec![format!("-DPATINA_YIELD_STRIDE={stride}")],
        ),
    };
    // Surface the instrumentation prominently: this binary is not a plain build —
    // it carries LLVM SanitizerCoverage, and `native-run` schedules it under a
    // distinct policy recorded in its compatibility fingerprint.
    let scheduler_hook = if instrumentation.preempts_inside_atomics() {
        "patina_yield_point"
    } else {
        "none"
    };
    let note = format!(
        "PATINA_NATIVE_BUILD_YIELD_POINTS instrumentation=llvm-sancov-trace-pc-guard \
mode={} scheduler-hook={scheduler_hook} fingerprint-suffix={} -- {}",
        instrumentation.mode_tag(),
        instrumentation.fingerprint_suffix(),
        instrumentation.describe()
    );
    if output::options().is_json() {
        eprintln!("{note}");
    } else {
        println!("{note}");
    }
    stage_shim_object(shim, object, host_target, &defines).map(Some)
}

/// Compile `object` to a stable, content-addressed path under `base` and return
/// it, reusing an already-staged object without recompiling. Staging is
/// race-safe: under its build lock the object is compiled in a private sandbox
/// to a fixed partial file, then atomically renamed into place. A retry clears
/// any interrupted partial. Production callers keep the artifact entry leased
/// until the guest link completes; eviction reclaims its helper objects together
/// with the archive.
pub(super) fn stage_shim_object(
    shim: &BuiltNativeShim,
    object: &ShimObject,
    target: &str,
    defines: &[String],
) -> Result<PathBuf, CliError> {
    let cc = env::var_os("CC").unwrap_or_else(|| OsString::from("cc"));
    let hash = shim_object_hash(&cc, object, target, defines)?;
    let dir = shim._lease.dir.join(NATIVE_SHIM_OBJECTS_DIR).join(hash);
    let _lock = lock_target_dir(&dir)?;
    let staged = dir.join(object.object_name);
    if staged.exists() {
        return Ok(staged);
    }
    fs::create_dir_all(&dir).map_err(|error| {
        CliError(format!(
            "failed to create the shim object cache {}: {error}",
            dir.display()
        ))
    })?;
    let sandbox = tempfile::tempdir().map_err(|error| {
        CliError(format!(
            "failed to create the shim compile sandbox: {error}"
        ))
    })?;
    let mut command = Command::new(&cc);
    command.args(object.cc_flags);
    command.args(defines);
    if let Some((header_name, header_source)) = object.header {
        fs::write(sandbox.path().join(header_name), header_source)
            .map_err(|error| CliError(format!("failed to stage {}: {error}", object.what)))?;
        command.arg("-I").arg(sandbox.path());
    }
    for (relative, source) in object.companion_sources {
        let path = sandbox.path().join(relative);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)
                .map_err(|error| CliError(format!("failed to stage {}: {error}", object.what)))?;
        }
        fs::write(&path, source)
            .map_err(|error| CliError(format!("failed to stage {}: {error}", object.what)))?;
    }
    let source_path = sandbox.path().join(object.source_name);
    fs::write(&source_path, object.source)
        .map_err(|error| CliError(format!("failed to stage {}: {error}", object.what)))?;
    let temp_object = dir.join("object.partial");
    shim_cache::clear_partial(&temp_object)?;
    shim_cache::inherit(&mut command, &shim._lease)?;
    command
        .arg("-c")
        .arg(&source_path)
        .arg("-o")
        .arg(&temp_object);
    let cc_status = command
        .status()
        .map_err(|error| CliError(format!("failed to run C compiler {cc:?}: {error}")))?;
    if !cc_status.success() {
        return Err(CliError(format!("compiling {} failed", object.what)));
    }
    fs::rename(&temp_object, &staged).map_err(|error| {
        CliError(format!(
            "failed to stage {} at {}: {error}",
            object.what,
            staged.display()
        ))
    })?;
    Ok(staged)
}

