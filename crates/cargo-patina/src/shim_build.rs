// The native link recipe is packaged into `cargo patina` so `native-build` can
// reproduce it without the source tree: the POSIX shim C layer and its header
// are embedded, compiled below the user program, and linked against the
// `patina-dst-native-shim` staticlib. The C text is sourced from the shim crate
// itself (its `pub const`s) rather than an `include_str!` across the crate
// boundary, so there is a single copy of the C that cannot drift and both
// crates package cleanly for publish.
const PATINA_POSIX_C: &str = patina_dst_native_shim::POSIX_C_SOURCE;
/// The per-family slices the umbrella `#include`s, staged beside it.
const PATINA_POSIX_C_FAMILIES: &[(&str, &str)] = patina_dst_native_shim::POSIX_C_FAMILY_SOURCES;
const PATINA_NATIVE_H: &str = patina_dst_native_shim::NATIVE_HEADER;
/// The embedded native-shim source bundle, generated by `build.rs`: the shim's
/// whole workspace dependency closure (12 crates) plus the pinning `Cargo.lock`,
/// content-addressed by `EMBEDDED_SHIM_BUNDLE_SHA256`. Carrying the source (not a
/// prebuilt staticlib) lets an installed `cargo-patina` compile the shim with the
/// exact rustc that compiles the guest — the identity the toolchain check pins.
mod shim_bundle {
    include!(concat!(env!("OUT_DIR"), "/shim_sources.rs"));
}

/// The content address of the shim source bundle this `cargo-patina` embeds,
/// in hex: the shim every native guest it builds links.
pub(super) fn embedded_shim_bundle_sha256() -> &'static str {
    shim_bundle::EMBEDDED_SHIM_BUNDLE_SHA256
}

const NATIVE_SHIM_STATICLIB: &str = "libpatina_dst_native_shim.a";
/// Subdirectory of the shim's own profile target dir where the content-addressed
/// POSIX/yield helper objects are staged, so their `-Clink-arg` paths stay stable
/// across builds and Cargo's crate fingerprints stay warm.
const NATIVE_SHIM_OBJECTS_DIR: &str = "patina-shim-objects";
/// Lock file in every Cargo target dir cargo-patina builds in; see
/// [`lock_target_dir`].
pub(super) const TARGET_DIR_LOCK: &str = ".patina-build.lock";

pub(super) fn link_arg(path: &Path) -> OsString {
    let mut arg = OsString::from("link-arg=");
    arg.push(path);
    arg
}

/// The per-user cache root that holds the unpacked shim source bundle and, by
/// default, its build: `$XDG_CACHE_HOME/patina` when set (any platform), else
/// `~/Library/Caches/patina` on macOS and `~/.cache/patina` elsewhere. No `HOME`
/// is a loud error, never a fallback into the working directory.
fn patina_cache_root() -> Result<PathBuf, CliError> {
    if let Some(xdg) = env::var_os("XDG_CACHE_HOME").filter(|value| !value.is_empty()) {
        let xdg = PathBuf::from(xdg);
        if !xdg.is_absolute() {
            return Err(CliError(format!(
                "XDG_CACHE_HOME must be an absolute path, got {}",
                xdg.display()
            )));
        }
        return Ok(xdg.join("patina"));
    }
    let home = env::var_os("HOME")
        .filter(|value| !value.is_empty())
        .ok_or_else(|| {
            CliError(
                "HOME is not set: cargo-patina places its shim source cache under it (or under \
                 XDG_CACHE_HOME when that is set)"
                    .into(),
            )
        })?;
    let home = PathBuf::from(home);
    Ok(if cfg!(target_os = "macos") {
        home.join("Library").join("Caches").join("patina")
    } else {
        home.join(".cache").join("patina")
    })
}

/// The unpacked shim source workspace, and the cache root it lives under.
pub(super) struct ShimSources {
    cache_root: PathBuf,
    /// `<cache_root>/shim-src/<bundle sha256>`: a self-contained Cargo workspace
    /// holding the shim's whole dependency closure, the pinning `Cargo.lock`, and
    /// no toolchain pin of its own.
    pub(super) dir: PathBuf,
    /// The content address of the embedded source bundle that produced `dir`.
    bundle_hash: &'static str,
    // Pins sources from before toolchain probing through the last guest link.
    _lease: shim_cache::Lease,
}

pub(super) struct BuiltNativeShim {
    pub(super) staticlib: PathBuf,
    // Guest builders must retain this, not just the path, until linking ends.
    pub(super) _lease: shim_cache::Lease,
}

impl BuiltNativeShim {
    /// The rustc `-C` values that route the allocator entry points of the
    /// compiler that built the archive through its arena router
    /// (`allocator_routing.rs`): the wraps, and the routing object staged for
    /// `host_target`. Empty where the platform routes nothing.
    pub(super) fn allocator_link_args(&self, host_target: &str) -> Result<Vec<OsString>, CliError> {
        Ok(self
            .allocator_routing(host_target)?
            .map(|(routing, object)| routing.link_args(&object, &self.staticlib))
            .unwrap_or_default())
    }

    /// [`Self::allocator_link_args`] as plain compiler-driver arguments, for a
    /// link rustc does not drive (a Go guest's external link).
    pub(super) fn allocator_linker_args(
        &self,
        host_target: &str,
    ) -> Result<Vec<OsString>, CliError> {
        Ok(self
            .allocator_routing(host_target)?
            .map(|(routing, object)| routing.linker_args(&object, &self.staticlib))
            .unwrap_or_default())
    }

    /// The archive's allocator routing and its staged object, or `None` where
    /// the platform routes nothing.
    fn allocator_routing(
        &self,
        host_target: &str,
    ) -> Result<Option<(crate::allocator_routing::AllocatorRouting, PathBuf)>, CliError> {
        let routing = crate::allocator_routing::AllocatorRouting::read(&self.staticlib)?;
        let Some(defines) = routing.defines() else {
            return Ok(None);
        };
        let object = stage_shim_object(
            self,
            &PATINA_ALLOCATOR_ROUTING_OBJECT,
            host_target,
            &defines,
        )?;
        Ok(Some((routing, object)))
    }
}

/// Unpack the embedded shim source bundle into the per-user cache (a no-op when
/// this binary's bundle is already there) and return where it lives.
///
/// `cargo-patina` carries the shim's source, not a prebuilt staticlib: the shim
/// must be compiled by the exact rustc that compiles the guest, so the build
/// happens on the user's machine, from a directory this binary owns. That is
/// what lets `build`/`run`/`audit`/`replay` of a source or package succeed from
/// any working directory and from an installed binary alike — `cargo build -p
/// patina-dst-native-shim` runs in a private copy of the unpacked workspace, never in the
/// caller's CWD (where the shim crate would not resolve) and never in a source
/// checkout (which an installed binary does not have).
pub(super) fn prepare_shim_sources() -> Result<ShimSources, CliError> {
    let cache_root = patina_cache_root()?;
    let lease = shim_cache::acquire_initialized(
        &cache_root.join("shim-src"),
        shim_bundle::EMBEDDED_SHIM_BUNDLE_SHA256,
        shim_cache::KEEP_SOURCES,
        || unpack_embedded_shim_sources(&cache_root).map(|_| ()),
    )?;
    Ok(ShimSources {
        cache_root,
        dir: lease.dir.clone(),
        bundle_hash: shim_bundle::EMBEDDED_SHIM_BUNDLE_SHA256,
        _lease: lease,
    })
}

/// Write the bundle to `<cache_root>/shim-src/<sha256>` atomically: stage into
/// a temporary sibling and rename into place, with a completion marker written
/// last. The caller holds the source catalog lock. Incomplete/old directories
/// are retired before repair; directory existence alone is never a cache hit.
fn unpack_embedded_shim_sources(cache_root: &Path) -> Result<PathBuf, CliError> {
    let bundles = cache_root.join("shim-src");
    let bundle_dir = bundles.join(shim_bundle::EMBEDDED_SHIM_BUNDLE_SHA256);
    if shim_cache::complete(&bundle_dir, shim_bundle::EMBEDDED_SHIM_BUNDLE_SHA256)? {
        return Ok(bundle_dir);
    }
    if bundle_dir.exists() {
        shim_cache::retire(&bundle_dir)?;
    }
    let io = |what: String, error: io::Error| CliError(format!("{what}: {error}"));
    fs::create_dir_all(&bundles)
        .map_err(|error| io(format!("creating {}", bundles.display()), error))?;
    let stage = tempfile::Builder::new()
        .prefix(".staging-")
        .tempdir_in(&bundles)
        .map_err(|error| {
            io(
                format!("staging shim sources in {}", bundles.display()),
                error,
            )
        })?;
    let staging = stage.path();
    let write = |relative: &Path, bytes: &[u8]| -> Result<(), CliError> {
        let path = staging.join(relative);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)
                .map_err(|error| io(format!("creating {}", parent.display()), error))?;
        }
        fs::write(&path, bytes).map_err(|error| io(format!("writing {}", path.display()), error))
    };
    let mut members = String::new();
    for (package, files) in shim_bundle::EMBEDDED_SHIM_SOURCES {
        members.push_str(&format!("    {package:?},\n"));
        for (relative, bytes) in *files {
            write(&Path::new(package).join(relative), bytes)?;
        }
    }
    // The unpacked closure is its own workspace: every member is addressed by
    // package name (its manifests were repointed to `../<package-name>` when the
    // bundle was packed), and the lock pins the third-party crates.
    write(
        Path::new("Cargo.toml"),
        format!(
            "# @generated by cargo-patina: the native shim's build workspace. Do not edit.\n\
             [workspace]\nmembers = [\n{members}]\nresolver = \"2\"\n"
        )
        .as_bytes(),
    )?;
    write(
        Path::new("Cargo.lock"),
        shim_bundle::EMBEDDED_SHIM_CARGO_LOCK,
    )?;
    write(
        Path::new(shim_cache::COMPLETE),
        shim_bundle::EMBEDDED_SHIM_BUNDLE_SHA256.as_bytes(),
    )?;
    fs::rename(staging, &bundle_dir).map_err(|error| {
        io(
            format!("publishing shim sources at {}", bundle_dir.display()),
            error,
        )
    })?;
    Ok(bundle_dir)
}

/// Build in reusable scratch state; publish and pin only immutable link inputs.
pub(super) fn build_native_shim(
    release: bool,
    rustc: &RustcInvocation,
    shim: &ShimSources,
    instrumentation: GuestInstrumentation,
) -> Result<BuiltNativeShim, CliError> {
    let explicit = shim_target_base(
        env::var_os("PATINA_SHIM_TARGET_DIR"),
        env::var_os("CARGO_TARGET_DIR"),
    );
    build_native_shim_at(release, rustc, shim, explicit.as_deref(), instrumentation)
}

/// `PATINA_SHIM_TARGET_DIR` sets the shim's base alone, so guest builds with
/// target dirs of their own can share one shim build; otherwise the shim
/// stages under `CARGO_TARGET_DIR`.
fn shim_target_base(
    shim_target_dir: Option<OsString>,
    cargo_target_dir: Option<OsString>,
) -> Option<OsString> {
    shim_target_dir
        .filter(|dir| !dir.is_empty())
        .or(cargo_target_dir)
}

fn build_native_shim_at(
    release: bool,
    rustc: &RustcInvocation,
    shim: &ShimSources,
    explicit: Option<&OsStr>,
    instrumentation: GuestInstrumentation,
) -> Result<BuiltNativeShim, CliError> {
    let base = native_shim_cache_base(&shim.cache_root, explicit)?;
    shim_cache::prune_legacy(&base);
    let profile = if release { "release" } else { "debug" };
    let mut hasher = Sha256::new();
    // Each profile builds in a work dir of its own, under its own lock: an
    // optimized single-unit release build takes far longer than a debug one,
    // and the debug shim every test guest links must not queue behind it.
    hash_bytes(&mut hasher, rustc.identity.verbose.as_bytes());
    hash_bytes(&mut hasher, profile.as_bytes());
    let work = shim_cache::acquire(
        &base.join("builds"),
        &hex(&hasher.finalize()),
        shim_cache::KEEP_BUILDS,
    )?;
    // Pin before waiting: the pruner must not unlink this lock's inode while a
    // second builder is queued. Only the Cargo build is serialized, not links.
    let _lock = lock_target_dir(&work.dir)?;
    let target_dir = work.dir.join("target");
    let source_dir = work.dir.join("source");
    let marker = work.dir.join("bundle");
    let previous = match fs::read_to_string(&marker) {
        Ok(value) => Some(value),
        Err(e) if e.kind() == io::ErrorKind::NotFound => None,
        Err(e) => return Err(CliError(format!("reading {}: {e}", marker.display()))),
    };
    let needs_switch = previous.as_deref() != Some(shim.bundle_hash)
        || !shim_cache::complete(&source_dir, shim.bundle_hash)?;
    // Size is a high-water mark, not a mid-build quota. A single build may be
    // larger; its next use resets scratch state without touching pinned links.
    shim_cache::trim_build_target(&work.dir);
    // The closure packages whose sources this build replaces, or `None` for a
    // whole reset. A switch from an intact previous bundle replaces only the
    // packages whose bytes differ, so their unchanged dependencies keep their
    // compiled artifacts; anything less certain resets every package.
    let mut replaced: Option<Vec<&str>> = Some(Vec::new());
    if needs_switch {
        let intact = match &previous {
            Some(previous) => shim_cache::complete(&source_dir, previous)?,
            None => false,
        };
        replaced = if intact {
            changed_packages(&shim.dir, &source_dir)?
        } else {
            None
        };
        // Invalidate BEFORE changing sources. A crash halfway through a switch
        // must not let the previous bundle mistake this workspace for its own,
        // and with no marker the retry resets every package.
        if previous.is_some() {
            fs::remove_file(&marker)
                .map_err(|e| CliError(format!("invalidating shim bundle marker: {e}")))?;
        }
        match &replaced {
            Some(packages) => {
                shim_cache::clear_partial(&source_dir.join(shim_cache::COMPLETE))?;
                shim_cache::copy(&shim.dir.join("Cargo.lock"), &source_dir.join("Cargo.lock"))?;
                for package in packages {
                    let dir = source_dir.join(package);
                    if dir.exists() {
                        fs::remove_dir_all(&dir)
                            .map_err(|e| CliError(format!("resetting shim build sources: {e}")))?;
                    }
                    shim_cache::copy_sources(&shim.dir.join(package), &dir)?;
                }
            }
            None => {
                if source_dir.exists() {
                    fs::remove_dir_all(&source_dir)
                        .map_err(|e| CliError(format!("resetting shim build sources: {e}")))?;
                }
                shim_cache::copy_sources(&shim.dir, &source_dir)?;
            }
        }
    }
    let command = || {
        let mut command = Command::new(&rustc.cargo_command);
        command
            .current_dir(&source_dir)
            .env("CARGO_TARGET_DIR", &target_dir)
            // Cargo >=1.91 can redirect intermediate state independently. Keep
            // it in our bounded scratch too; older Cargo ignores this variable.
            .env("CARGO_BUILD_BUILD_DIR", &target_dir)
            // A debug shim keeps incremental history: the single codegen unit
            // the guest archive needs (`POSIX_RUST_FLAGS`) makes every shim
            // edit regenerate all of the crate's code, and incremental reuse
            // of the rest of the compilation more than halves the rebuild. A
            // release shim, rebuilt rarely, keeps none. Neither needs full
            // type debug info: level 1 retains backtraces and source locations.
            .env("CARGO_INCREMENTAL", if release { "0" } else { "1" })
            .env("CARGO_PROFILE_DEV_DEBUG", "1");
        apply_rustc_env(&mut command, rustc);
        command
    };
    if needs_switch {
        // Never trust Cargo's freshness of replaced sources: a copy can keep
        // timestamps older than the previous bundle's artifacts. Clean only the
        // replaced local closure packages: registry dependencies and unchanged
        // packages stay reusable. This also bounds obsolete local artifacts as
        // source versions change.
        let cleaned: Vec<&str> = match &replaced {
            Some(packages) => packages.clone(),
            None => shim_bundle::EMBEDDED_SHIM_SOURCES
                .iter()
                .map(|(package, _)| *package)
                .collect(),
        };
        if !cleaned.is_empty() {
            // The clean forces the rebuild; the packages' incremental histories
            // survive it, since rustc verifies every reuse against the sources.
            let kept = shim_cache::IncrementalHistory::set_aside(&target_dir, &cleaned)?;
            let mut clean = command();
            shim_cache::inherit(&mut clean, &work)?;
            clean.arg("clean");
            for package in &cleaned {
                clean.arg("-p").arg(package);
            }
            let status = clean
                .status()
                .map_err(|e| CliError(format!("cleaning shim packages: {e}")))?;
            if !status.success() {
                return Err(CliError("cleaning shim packages failed".into()));
            }
            kept.restore();
        }
        // Write only after successful invalidation. A crash or failed build
        // leaves Cargo's own incomplete-build fingerprint to force a retry.
        fs::write(source_dir.join(shim_cache::COMPLETE), shim.bundle_hash)
            .map_err(|e| CliError(format!("completing shim build sources: {e}")))?;
        fs::write(&marker, shim.bundle_hash)
            .map_err(|e| CliError(format!("writing shim bundle marker: {e}")))?;
    }
    let mut build = command();
    shim_cache::inherit(&mut build, &work)?;
    build.args(["rustc", "--lib", "--locked", "-p", "patina-dst-native-shim"]);
    if release {
        build.arg("--release");
    }
    build
        .arg("--")
        .args(patina_dst_native_shim::POSIX_RUST_FLAGS);
    let status = build
        .status()
        .map_err(|e| CliError(format!("building shim: {e}")))?;
    if !status.success() {
        return Err(CliError(
            "building the patina-dst-native-shim staticlib failed".into(),
        ));
    }
    let staticlib = target_dir.join(profile).join(NATIVE_SHIM_STATICLIB);
    // C compiler and instrumentation variants get independently evictable
    // entries, rather than accumulating objects inside one eternally hot entry.
    let cc = env::var_os("CC").unwrap_or_else(|| "cc".into());
    let c_identity = shim_object_hash(&cc, &PATINA_POSIX_OBJECT, &host_target_triple(rustc)?, &[])?;
    let recipe = format!("{profile}:{c_identity}:{instrumentation:?}");
    publish_native_shim(
        &staticlib,
        &base,
        shim.bundle_hash,
        &rustc.identity,
        &recipe,
    )
}

/// The closure packages whose sources differ between the bundle `bundle` and
/// the private build copy `copy`, or `None` when anything else at the
/// workspace root differs (its manifest, Cargo configuration), which only a
/// whole reset handles. The lock is not compared: Cargo rewrites the copy's
/// (a newer lock format), the switch restores the bundle's, and Cargo
/// fingerprints the dependency versions it resolves.
fn changed_packages<'a>(bundle: &Path, copy: &Path) -> Result<Option<Vec<&'a str>>, CliError> {
    let package = |name: &std::ffi::OsStr| {
        shim_bundle::EMBEDDED_SHIM_SOURCES
            .iter()
            .any(|(package, _)| name == std::ffi::OsStr::new(package))
    };
    let mut root = BTreeSet::new();
    for dir in [bundle, copy] {
        for entry in fs::read_dir(dir).map_err(|e| CliError(format!("{}: {e}", dir.display())))? {
            let name = entry
                .map_err(|e| CliError(format!("{}: {e}", dir.display())))?
                .file_name();
            if !package(&name) && name != "Cargo.lock" && !shim_cache::cache_metadata(&name) {
                root.insert(name);
            }
        }
    }
    for name in root {
        if !shim_cache::same_tree(&bundle.join(&name), &copy.join(&name))? {
            return Ok(None);
        }
    }
    let mut changed = Vec::new();
    for (package, _) in shim_bundle::EMBEDDED_SHIM_SOURCES {
        if !shim_cache::same_tree(&bundle.join(package), &copy.join(package))? {
            changed.push(*package);
        }
    }
    Ok(Some(changed))
}

/// The archive digest also distinguishes ambient Cargo configuration changes.
/// Publication is an atomic file rename; helper objects are likewise published
/// atomically below the pinned entry and are never read from Cargo scratch.
fn publish_native_shim(
    staticlib: &Path,
    base: &Path,
    bundle: &str,
    toolchain: &RustcIdentity,
    profile: &str,
) -> Result<BuiltNativeShim, CliError> {
    let mut hasher = Sha256::new();
    hash_file_contents(&mut hasher, staticlib)?;
    hash_bytes(&mut hasher, bundle.as_bytes());
    hash_bytes(&mut hasher, toolchain.verbose.as_bytes());
    hash_bytes(&mut hasher, profile.as_bytes());
    let lease = shim_cache::acquire(
        &base.join("artifacts"),
        &hex(&hasher.finalize()),
        shim_cache::KEEP_ARTIFACTS,
    )?;
    let _lock = lock_target_dir(&lease.dir)?;
    let published = lease.dir.join(NATIVE_SHIM_STATICLIB);
    let partial = lease.dir.join("archive.partial");
    shim_cache::clear_partial(&partial)?;
    if !published.exists() {
        shim_cache::copy(staticlib, &partial)?;
        fs::rename(&partial, &published)
            .map_err(|e| CliError(format!("publishing shim archive: {e}")))?;
    }
    Ok(BuiltNativeShim {
        staticlib: published,
        _lease: lease,
    })
}

/// Hold `target_dir`'s build lock until the returned file is dropped; the
/// kernel releases it if the process dies.
///
/// Cargo rewrites every output in its target dir on every invocation, fresh or
/// not, wherever it copies rather than hard-links (always on macOS; on Linux
/// when the build dir is on another filesystem), and its own lock ends when
/// Cargo exits. A caller that reads an output back after Cargo returns — the
/// shim archive it publishes, the guest executable it copies out — therefore
/// holds this from before its Cargo invocation until that read is done, or a
/// concurrent build's Cargo can rewrite the file mid-read. OpenOptions creates
/// CLOEXEC descriptors on Unix; keep that flag set for build and catalog locks
/// so a compiler wrapper's daemon cannot retain an exclusive lock after exec.
pub(super) fn lock_target_dir(target_dir: &Path) -> Result<fs::File, CliError> {
    fs::create_dir_all(target_dir).map_err(|error| {
        CliError(format!(
            "failed to create target dir {}: {error}",
            target_dir.display()
        ))
    })?;
    let path = target_dir.join(TARGET_DIR_LOCK);
    let file = OpenOptions::new()
        .write(true)
        .create(true)
        .truncate(false)
        .open(&path)
        .map_err(|error| CliError(format!("failed to open {}: {error}", path.display())))?;
    lock_exclusive(&file, true)
        .map_err(|error| CliError(format!("failed to lock {}: {error}", path.display())))?;
    Ok(file)
}

/// Explicit CARGO_TARGET_DIR remains the base, never a replacement for Patina's
/// namespace. Anchor relative paths before Cargo changes into the source cache.
fn native_shim_cache_base(
    cache_root: &Path,
    explicit: Option<&OsStr>,
) -> Result<PathBuf, CliError> {
    let base = explicit
        .map(PathBuf::from)
        .unwrap_or_else(|| cache_root.join("shim-target"));
    std::path::absolute(base.join("patina-native-shim"))
        .map_err(|e| CliError(format!("resolving shim cache base: {e}")))
}

/// A resolved rustc, as `rustc -vV` reports it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(super) struct RustcIdentity {
    /// The `rustc -vV` banner line, e.g. `rustc 1.98.1 (48a229cea 2026-09-01)`.
    banner: String,
    /// The full `-vV` block: release, commit hash, host triple, LLVM version.
    pub(super) verbose: String,
}

#[derive(Debug, Clone)]
pub(super) struct RustcInvocation {
    pub(super) command: OsString,
    pub(super) cargo_command: OsString,
    pub(super) identity: RustcIdentity,
}

fn rustc_invocation_from_env(from: &Path) -> (OsString, Option<OsString>) {
    (
        anchored_program(env::var_os("RUSTC"), from, "rustc"),
        env::var_os("CARGO").map(|cargo| anchored_program(Some(cargo), from, "cargo")),
    )
}

pub(super) fn apply_rustc_env(command: &mut Command, rustc: &RustcInvocation) {
    command.env("RUSTC", &rustc.command);
}

/// Resolve the rustc that compiles code in `directory`.
///
/// The working directory is the input that matters. Under rustup, the `rustc` on
/// `PATH` is a proxy that picks its toolchain from the `rust-toolchain.toml`
/// found by walking up from wherever it runs, and Cargo inherits that: even a
/// toolchain's own `cargo` binary invokes the `PATH` proxy for `rustc`, so the
/// directory a build runs in — not the `cargo` that drives it — can decide which
/// compiler compiles the crate. Other directory-scoped selectors behave likewise;
/// a concrete compiler should report the same identity from every directory.
fn rustc_identity(rustc: &OsStr, directory: &Path) -> Result<RustcIdentity, CliError> {
    let output = Command::new(rustc)
        .arg("-vV")
        .current_dir(directory)
        .output()
        .map_err(|error| {
            CliError(format!(
                "failed to query the rustc identity in {}: {error}",
                directory.display()
            ))
        })?;
    if !output.status.success() {
        return Err(CliError(format!(
            "rustc -vV failed in {}: {}",
            directory.display(),
            String::from_utf8_lossy(&output.stderr).trim()
        )));
    }
    let verbose = String::from_utf8_lossy(&output.stdout).trim().to_owned();
    let banner = verbose.lines().next().unwrap_or_default().to_owned();
    if banner.is_empty() {
        return Err(CliError(format!(
            "rustc -vV reported no version in {}",
            directory.display()
        )));
    }
    Ok(RustcIdentity { banner, verbose })
}

/// The compiler to probe with, honoring `RUSTC` exactly as the builds do so an
/// explicitly pinned compiler probes as the single identity it is.
///
/// The two probes run in two different directories, so the value must name the
/// same program from both. A bare name is left alone (the OS resolves it against
/// `PATH`, which does not depend on the working directory); a relative path with
/// a directory component would resolve against each probe's own directory, so it
/// is anchored to `from` first.
fn anchored_program(program: Option<OsString>, from: &Path, fallback: &str) -> OsString {
    let Some(program) = program else {
        return OsString::from(fallback);
    };
    let path = Path::new(&program);
    let has_directory = path
        .parent()
        .is_some_and(|parent| !parent.as_os_str().is_empty());
    if path.is_relative() && has_directory {
        from.join(path).into_os_string()
    } else {
        program
    }
}

/// Materialize the guest compiler once; never resolve an ambient compiler in
/// the shared shim cache. Two stdlibs cause a duplicate rust_eh_personality on
/// Linux and can silently link on macOS.
///
/// A -vV banner is an identity, NOT a selector: it cannot encode a rustup name,
/// `stable`, a mise version, or a Nix path. RUSTUP_TOOLCHAIN / +toolchain are
/// rustup-specific, and writing rust-toolchain.toml into the content-addressed
/// bundle would mutate shared input and race concurrent builds. Instead verify
/// the sysroot's absolute compiler in BOTH directories and use it everywhere.
pub(super) fn check_native_toolchain_agreement(
    shim_dir: &Path,
) -> Result<RustcInvocation, CliError> {
    let guest_dir = env::current_dir()
        .map_err(|error| CliError(format!("failed to read the working directory: {error}")))?;
    let (selected, explicit_cargo) = rustc_invocation_from_env(&guest_dir);
    let refusal = |reason: String| {
        CliError(format!(
            "refusing to build: cannot prove one rustc toolchain for the guest in {} and the shim in {}: {reason}\n\
         invoke cargo-patina with absolute, matching RUSTC and CARGO binaries from one toolchain; \
         the compiler must expose a sysroot with bin/rustc and bin/cargo. No ambient fallback is used.",
            guest_dir.display(),
            shim_dir.display()
        ))
    };
    let guest = rustc_identity(&selected, &guest_dir).map_err(|e| refusal(e.0))?;
    let output = Command::new(&selected)
        .args(["--print", "sysroot"])
        .current_dir(&guest_dir)
        .output()
        .map_err(|e| {
            refusal(format!(
                "guest toolchain {}: failed to query sysroot: {e}",
                guest.banner
            ))
        })?;
    if !output.status.success() {
        return Err(refusal(format!(
            "guest toolchain {}: rustc --print sysroot failed: {}",
            guest.banner,
            String::from_utf8_lossy(&output.stderr).trim()
        )));
    }
    let sysroot = std::str::from_utf8(&output.stdout)
        .map_err(|e| refusal(format!("invalid sysroot: {e}")))?
        .trim();
    let sysroot = Path::new(sysroot);
    if !sysroot.is_absolute() {
        return Err(refusal(format!(
            "guest toolchain {}: sysroot is not an absolute path: {sysroot:?}",
            guest.banner
        )));
    }
    let command = sysroot.join("bin/rustc").into_os_string();
    let cargo = sysroot.join("bin/cargo");
    if !Path::new(&command).is_file() || !cargo.is_file() {
        return Err(refusal(format!(
            "guest toolchain {}: missing bin/rustc or bin/cargo in {}",
            guest.banner,
            sysroot.display()
        )));
    }
    for directory in [&guest_dir, shim_dir] {
        let verified = rustc_identity(&command, directory).map_err(|e| refusal(e.0))?;
        if verified != guest {
            return Err(CliError(toolchain_mismatch_message(
                &verified, directory, &guest, &guest_dir,
            )));
        }
    }
    Ok(RustcInvocation {
        command,
        cargo_command: explicit_cargo.unwrap_or_else(|| cargo.into_os_string()),
        identity: guest,
    })
}

/// Name the selected and materialized identities and the verification directory,
/// with a proxy-agnostic remedy. Never turn an identity banner into a selector.
fn toolchain_mismatch_message(
    shim: &RustcIdentity,
    shim_dir: &Path,
    guest: &RustcIdentity,
    guest_dir: &Path,
) -> String {
    let mut message = String::from(
        "refusing to build: the Patina shim staticlib and the guest program would be compiled by \
two different rustc toolchains, so two Rust standard libraries would meet at the guest link \
(`duplicate symbol: rust_eh_personality` on Linux; on macOS the link silently succeeds and the \
guest carries both).\n",
    );
    message.push_str(&format!(
        "  shim toolchain:  {} (resolved in {})\n  guest toolchain: {} (resolved in {})\n",
        shim.banner,
        shim_dir.display(),
        guest.banner,
        guest_dir.display()
    ));
    if shim.banner == guest.banner {
        // Same release, different compiler: show the full identities so the
        // difference (commit hash, host triple, LLVM version) is visible.
        message.push_str(&format!(
            "the two report the same version but are not the same compiler:\n  shim:\n{}\n  \
guest:\n{}\n",
            indent_lines(&shim.verbose, "    "),
            indent_lines(&guest.verbose, "    ")
        ));
    }
    message.push_str(
        "the absolute compiler in the guest's sysroot could not be verified against the \
selected guest identity. No ambient fallback is used. Invoke cargo-patina with absolute, matching \
RUSTC and CARGO binaries from one toolchain.",
    );
    message
}

/// Prefix every line of `text` with `indent`.
fn indent_lines(text: &str, indent: &str) -> String {
    text.lines()
        .map(|line| format!("{indent}{line}"))
        .collect::<Vec<_>>()
        .join("\n")
}

/// A shim helper object compiled below the guest and linked into every native
/// build. Both variants are content-addressed by [`stage_shim_object`]: the POSIX
/// layer always, the `--yield-points` hook only under that flag.
pub(super) struct ShimObject {
    /// Final object file name, e.g. `patina_posix.o`.
    object_name: &'static str,
    /// C translation-unit file name written into the compile sandbox.
    source_name: &'static str,
    /// Embedded C source compiled into the object.
    source: &'static str,
    /// Header staged beside the source and reached through `-I`, if any.
    header: Option<(&'static str, &'static str)>,
    /// Further sources the translation unit `#include`s by relative path,
    /// staged beside it (subdirectories created) and folded into the hash.
    companion_sources: &'static [(&'static str, &'static str)],
    /// `cc` flags, excluding `-c`/`-I`/the input path/`-o` (added by the stager).
    cc_flags: &'static [&'static str],
    /// What the object is, for staging/compilation diagnostics.
    what: &'static str,
}

