/// The arguments of call `nr` the kernel reads; the rest are zero.
pub fn used_args(nr: u64, args: &[u64; 6]) -> [u64; 6] {
    let n = if (nr as usize) < NR_COUNT {
        NARGS[nr as usize] as usize
    } else {
        6
    };
    let mut r = [0u64; 6];
    r[..n].copy_from_slice(&args[..n]);
    r
}
